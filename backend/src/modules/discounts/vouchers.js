'use strict';

/**
 * Vouchers (discounts PR 2). A manager (`discount.manage`) creates a voucher; a cashier (`discount.apply`) redeems it by
 * typing its code. The client sends ONLY the code: the type, value and cap come from the voucher, and the money is
 * worked out by the same `applyDiscounts` every discount uses. A voucher is an order-level discount, so the PR 1 rule
 * of one order-level discount per check keeps it from stacking with a manual one.
 *
 * Creation respects the creator's own limit. A percent voucher may take off at most the creator's role limit, and a
 * fixed one at most that share of any check it is used on (`check_percent_cap`); more than that, and a 100% voucher,
 * need comp authority and an explicit `override_limit`.
 *
 * A code is generated by the server, stored normalised, and shown with dashes. Every way a typed code can fail at the
 * till is the same error, so a code cannot be probed.
 */

const { ValidationError } = require('../../shared/errors');
const { toCents } = require('../../shared/money');
const { maxDiscountAmount } = require('../../shared/discount-input');
const { applyDiscounts, effectivePercent, isWithinPercentLimit } = require('../../shared/discount-pricing');
const { generateVoucherCode, normalizeVoucherCode, formatVoucherCode, isPlausibleVoucherCode } = require('../../shared/voucher-code');
const outletMenu = require('../../shared/outlet-menu');
const { roleAtProperty } = require('../../auth/roles');
const { hasPermission } = require('../../auth/rbac');
const posErrors = require('../pos/errors');
const store = require('./store');
const voucherStore = require('./voucher-store');
const errors = require('./errors');

const VOUCHER_REASON = { code: 'voucher', name: 'Voucher', kind: 'voucher' };
const CART_GRANT_TTL_MS = 30 * 60_000;
const MAX_CART_LINES = 100;
const MAX_USES = 1_000_000;
const ISO_DATE = /^\d{4}-\d{2}-\d{2}$/;

function invalid(message, field, issue = 'invalid') {
  return new ValidationError('INVALID_VOUCHER', message, [{ field, issue }]);
}

const isRealDate = (text) => ISO_DATE.test(text) && !Number.isNaN(Date.parse(`${text}T00:00:00Z`)) && new Date(`${text}T00:00:00Z`).toISOString().slice(0, 10) === text;
const decimal = (value) => typeof value === 'string' && /^\d+(\.\d{1,2})?$/.test(value.trim());

// ---------------------------------------------------------------- the voucher reason

/** The property's "Voucher" reason (every discount carries a reason). Created the first time one is needed; hidden from the pickers. */
async function ensureVoucherReason(db) {
  const existing = await db.table('discount_reasons').where({ code: VOUCHER_REASON.code }).first();
  if (existing) return existing;
  try {
    await db.table('discount_reasons').insert({ ...VOUCHER_REASON, status: 'active' });
  } catch (error) {
    if (error.code !== 'ER_DUP_ENTRY') throw error;
  }
  return db.table('discount_reasons').where({ code: VOUCHER_REASON.code }).first();
}

// ---------------------------------------------------------------- management

function shapeVoucher(row, outletIds = []) {
  return {
    id: String(row.id),
    code: formatVoucherCode(row.code),
    type: row.type,
    value: String(row.value),
    max_amount: row.max_amount === null || row.max_amount === undefined ? null : String(row.max_amount),
    check_percent_cap: String(row.check_percent_cap),
    valid_from: String(row.valid_from).slice(0, 10),
    valid_to: String(row.valid_to).slice(0, 10),
    max_total_uses: row.max_total_uses === null || row.max_total_uses === undefined ? null : Number(row.max_total_uses),
    used_count: Number(row.used_count),
    status: row.status,
    note: row.note ?? null,
    outlet_ids: outletIds.map(String),
    created_by_user_id: String(row.created_by_user_id),
    disabled_reason: row.disabled_reason ?? null,
  };
}

async function readCreateInput(trx, raw, businessDate) {
  const body = raw ?? {};
  if (!['percent', 'fixed'].includes(body.type)) throw invalid('"type" must be percent or fixed.', 'type');
  if (!decimal(body.value)) throw invalid('"value" must be an amount with at most 2 decimal places, e.g. "10" or "2.50".', 'value');
  const value = body.value.trim();
  const cents = toCents(value);
  if (cents <= 0n) throw invalid('"value" must be above zero.', 'value', 'not_positive');
  if (body.type === 'percent' && cents > 10000n) throw invalid('A percent voucher cannot be more than 100.', 'value', 'too_large');
  if (body.type === 'fixed' && cents > toCents(maxDiscountAmount())) throw invalid(`A fixed voucher must not exceed ${maxDiscountAmount()}.`, 'value', 'too_large');

  let maxAmount = null;
  if (body.max_amount !== undefined && body.max_amount !== null) {
    if (!decimal(body.max_amount) || toCents(body.max_amount.trim()) <= 0n) throw invalid('"max_amount" must be an amount above zero with at most 2 decimals.', 'max_amount');
    maxAmount = body.max_amount.trim();
  }

  const validFrom = body.valid_from === undefined || body.valid_from === null ? businessDate : body.valid_from;
  if (typeof validFrom !== 'string' || !isRealDate(validFrom)) throw invalid('"valid_from" must be a date, YYYY-MM-DD.', 'valid_from');
  if (typeof body.valid_to !== 'string' || !isRealDate(body.valid_to)) throw invalid('"valid_to" is required, as YYYY-MM-DD.', 'valid_to');
  if (body.valid_to < validFrom) throw invalid('"valid_to" must not be before "valid_from".', 'valid_to', 'before_valid_from');
  if (businessDate && body.valid_to < businessDate) throw invalid('"valid_to" is already in the past.', 'valid_to', 'in_past');

  let maxTotalUses = null;
  if (body.max_total_uses !== undefined && body.max_total_uses !== null) {
    if (!Number.isInteger(body.max_total_uses) || body.max_total_uses < 1 || body.max_total_uses > MAX_USES) throw invalid('"max_total_uses" must be a whole number of at least 1.', 'max_total_uses');
    maxTotalUses = body.max_total_uses;
  }

  let note = null;
  if (body.note !== undefined && body.note !== null) {
    if (typeof body.note !== 'string' || body.note.trim().length > 200) throw invalid('"note" must be text of at most 200 characters.', 'note');
    note = body.note.trim() || null;
  }

  const outletIds = [];
  if (body.outlet_ids !== undefined && body.outlet_ids !== null) {
    if (!Array.isArray(body.outlet_ids) || body.outlet_ids.length > 100) throw invalid('"outlet_ids" must be a list of outlets.', 'outlet_ids');
    for (const id of body.outlet_ids) {
      if (!/^\d+$/.test(String(id))) throw invalid('"outlet_ids" must be a list of outlets.', 'outlet_ids');
      outletIds.push(String(id));
    }
    const unique = [...new Set(outletIds)];
    const found = unique.length ? await trx.table('pos_outlets').whereIn('id', unique).select('id') : [];
    if (found.length !== unique.length) throw invalid('One of the outlets is not an outlet of this property.', 'outlet_ids', 'not_found');
    outletIds.splice(0, outletIds.length, ...unique);
  }
  return { type: body.type, value, maxAmount, validFrom, validTo: body.valid_to, maxTotalUses, note, outletIds, overrideLimit: body.override_limit === true };
}

/** Creates a voucher. The creator's own discount limit bounds it; anything beyond needs comp authority. */
async function createVoucher({ trx, raw, userId }) {
  const businessDate = await voucherStore.propertyBusinessDate(trx, trx.context.propertyId);
  const input = await readCreateInput(trx, raw, businessDate);
  const role = await roleAtProperty(trx, trx.context, userId, trx.context.propertyId);
  const limit = role ? await store.limitPercentFor(trx, role) : '0.00';
  const holdsComp = role ? await hasPermission(trx, role, 'discount.comp') : false;

  if (input.overrideLimit && !holdsComp) throw new errors.VoucherNeedsCompError();
  const wholeBill = input.type === 'percent' && toCents(input.value) === 10000n;
  if (wholeBill && !holdsComp) throw new errors.VoucherNeedsCompError();
  if (input.type === 'percent' && !input.overrideLimit && !wholeBill && !isWithinPercentLimit({ amount: input.value, base: '100.00', limitPercent: limit })) {
    throw new errors.VoucherAboveLimitError(limit);
  }
  // A 100% voucher can only be a comp-authority one, so it is never bounded by the check.
  const checkPercentCap = input.overrideLimit || wholeBill ? '100.00' : limit;

  let id = null;
  for (let attempt = 0; attempt < 5 && id === null; attempt += 1) {
    try {
      [id] = await trx.table('vouchers').insert({
        code: generateVoucherCode(),
        type: input.type,
        value: input.value,
        max_amount: input.maxAmount,
        check_percent_cap: checkPercentCap,
        valid_from: input.validFrom,
        valid_to: input.validTo,
        max_total_uses: input.maxTotalUses,
        note: input.note,
        created_by_user_id: userId,
      });
    } catch (error) {
      if (error.code !== 'ER_DUP_ENTRY') throw error; // a code collision: draw another
    }
  }
  if (id === null) throw new Error('Could not generate a unique voucher code.');
  for (const outletId of input.outletIds) await trx.table('voucher_outlets').insert({ voucher_id: id, outlet_id: outletId });
  const row = await trx.table('vouchers').where({ id }).first();
  return shapeVoucher(row, input.outletIds);
}

async function listVouchers({ db }) {
  const rows = await db.table('vouchers').orderBy('id', 'desc').limit(500);
  const links = rows.length ? await db.table('voucher_outlets').whereIn('voucher_id', rows.map((row) => row.id)) : [];
  const byVoucher = new Map();
  for (const link of links) byVoucher.set(String(link.voucher_id), [...(byVoucher.get(String(link.voucher_id)) ?? []), link.outlet_id]);
  return rows.map((row) => shapeVoucher(row, byVoucher.get(String(row.id)) ?? []));
}

async function setVoucherStatus({ trx, id, to, userId, reason }) {
  const before = await trx.table('vouchers').where({ id }).forUpdate().first();
  if (!before) throw new errors.VoucherNotFoundError();
  if (before.status === to) throw new errors.DiscountStateError(id, to);
  if (to === 'disabled') {
    await trx.table('vouchers').where({ id }).update({ status: 'disabled', disabled_by_user_id: userId, disabled_at: new Date(), disabled_reason: reason });
  } else {
    await trx.table('vouchers').where({ id }).update({ status: 'active', disabled_by_user_id: null, disabled_at: null, disabled_reason: null });
  }
  const after = await trx.table('vouchers').where({ id }).first();
  return { before: shapeVoucher(before, await voucherStore.outletIdsOf(trx, id)), after: shapeVoucher(after, await voucherStore.outletIdsOf(trx, id)) };
}

// ---------------------------------------------------------------- redeeming a code at the till

/** The voucher a typed code names, or null. Never throws for a bad code: callers answer with the one generic error. */
async function findByCode(trx, rawCode) {
  const normalised = normalizeVoucherCode(rawCode);
  if (!isPlausibleVoucherCode(normalised)) return null;
  return (await trx.table('vouchers').where({ code: normalised }).first()) ?? null;
}

/** The voucher a code names, locked for this transaction (re-read under the lock), or null. */
async function lockVoucherByCode(trx, rawCode) {
  const found = await findByCode(trx, rawCode);
  return found ? (await trx.table('vouchers').where({ id: found.id }).forUpdate().first()) ?? null : null;
}

/** Validates a voucher for an outlet today (one generic error) and prices it against the items, enforcing the check cap. */
async function priceVoucher(trx, { voucher, outlet, items, activeRows }) {
  const businessDate = await voucherStore.propertyBusinessDate(trx, trx.context.propertyId);
  const outletIds = voucher ? await voucherStore.outletIdsOf(trx, voucher.id) : [];
  if (!voucher || voucherStore.problemFor(voucher, { outletId: outlet.id, businessDate, outletIds })) throw new errors.VoucherInvalidError();

  const pricing = applyDiscounts({
    items,
    discounts: [...activeRows, { id: 'new', scope: 'order', type: voucher.type, value: String(voucher.value), max_amount: voucher.max_amount === null ? null : String(voucher.max_amount) }],
  });
  const entry = pricing.discounts.find((candidate) => candidate.discountId === 'new');
  if (toCents(entry.baseBefore) <= 0n || toCents(entry.amount) <= 0n) throw new errors.DiscountNothingToDiscountError();
  if (toCents(entry.amount) >= toCents(entry.baseBefore)) throw new errors.DiscountUseCompError();
  // The reference for a fixed voucher is the check it is used on: it may take off at most its creator's share of it.
  if (!isWithinPercentLimit({ amount: entry.amount, base: entry.baseBefore, limitPercent: String(voucher.check_percent_cap) })) {
    throw new errors.VoucherCheckTooSmallError(String(voucher.check_percent_cap));
  }
  return { amount: entry.amount, effectivePercent: effectivePercent({ amount: entry.amount, base: entry.baseBefore }) };
}

async function insertVoucherDiscount(trx, { voucher, outlet, orderId, evaluation, userId, extra = {} }) {
  const reason = await ensureVoucherReason(trx);
  const [id] = await trx.table('discounts').insert({
    outlet_id: outlet.id,
    pos_order_id: orderId,
    scope: 'order',
    kind: 'voucher',
    type: voucher.type,
    value: voucher.value,
    reason_id: reason.id,
    status: 'active',
    effective_percent: evaluation.effectivePercent,
    applied_by_user_id: userId,
    // The manager who created the voucher authorised it; that is the approval, so no limit check or PIN is asked of the cashier.
    approved_by_user_id: voucher.created_by_user_id,
    decided_at: new Date(),
    // The voucher's own cap, if it has one. Not frozen at the amount it came to: items added later are covered up to the cap.
    max_amount: voucher.max_amount,
    ...extra,
  });
  await trx.table('voucher_redemptions').insert({ voucher_id: voucher.id, discount_id: id, outlet_id: outlet.id, code: voucher.code, status: 'attached', attached_by_user_id: userId });
  return trx.table('discounts').where({ id }).first();
}

/** A voucher code typed on an open Register check. `assertTab(order)` is the tab-owner rule (pos/service.js). */
async function attachToOrder({ trx, orderId, code, userId, assertTab }) {
  const order = await trx.table('pos_orders').where({ id: orderId }).forUpdate().first();
  if (!order) throw new posErrors.OrderNotFoundError();
  if (order.status !== 'open') throw new posErrors.OrderNotOpenError(orderId, order.status);
  const ownerOverride = assertTab ? assertTab(order) : null;
  if (await store.hasCapturedUnsettledPayment(trx, orderId)) throw new errors.DiscountPaymentInProgressError();

  // The voucher is locked BEFORE the check's discounts are read with a locking read (which takes gap locks on the
  // discounts index): the same order settlement uses, so two checks sharing a code queue on the voucher holding no gap
  // lock, instead of each waiting for a gap the other holds. A code that names nothing is the one generic error.
  const voucher = await lockVoucherByCode(trx, code);
  const items = await trx.table('pos_order_items').where({ pos_order_id: orderId }).whereNull('voided_at').forShare();
  const live = await trx.table('discounts').where({ pos_order_id: orderId }).whereIn('status', ['active', 'pending_approval']).forShare();
  if (live.some((row) => row.scope === 'order')) throw new errors.DiscountAlreadyOnTargetError('order');

  const outlet = await trx.table('pos_outlets').where({ id: order.outlet_id }).first();
  const evaluation = await priceVoucher(trx, { voucher, outlet, items, activeRows: live.filter((row) => row.status === 'active') });
  const row = await insertVoucherDiscount(trx, { voucher, outlet, orderId, evaluation, userId });
  return { discount: row, amount: evaluation.amount, ownerOverride, voucher };
}

/** A voucher code typed at the supermarket till BEFORE the sale exists: bound to this cashier and outlet until the sale claims it. */
async function attachToCart({ trx, outlet, cart, code, userId }) {
  if (!Array.isArray(cart) || cart.length === 0 || cart.length > MAX_CART_LINES) {
    throw new ValidationError('MISSING_FIELD', 'The cart is needed to price a voucher.', [{ field: 'items', issue: 'missing' }]);
  }
  const items = [];
  for (const [index, line] of cart.entries()) {
    const menuItem = await outletMenu.menuItemAtOutlet(trx, outlet.id, line?.menu_item_id);
    const quantity = Number(line?.quantity);
    if (!menuItem || !Number.isInteger(quantity) || quantity < 1 || quantity > 999) {
      throw new ValidationError('INVALID_CART', `Line ${index + 1} cannot be priced.`, [{ field: `items[${index}]`, issue: 'invalid' }]);
    }
    items.push({ id: index + 1, menu_item_id: menuItem.id, unit_price: menuItem.price, quantity, split_group: null, modifiers: [] });
  }
  const voucher = await lockVoucherByCode(trx, code);
  const evaluation = await priceVoucher(trx, { voucher, outlet, items, activeRows: [] });
  const row = await insertVoucherDiscount(trx, { voucher, outlet, orderId: null, evaluation, userId, extra: { expires_at: new Date(Date.now() + CART_GRANT_TTL_MS) } });
  return { discount: row, amount: evaluation.amount, voucher };
}

module.exports = { createVoucher, listVouchers, setVoucherStatus, attachToOrder, attachToCart, ensureVoucherReason, shapeVoucher, VOUCHER_REASON };
